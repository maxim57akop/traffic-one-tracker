export type TranslationKey = keyof typeof translations.en;

function readLanguage(): Language {
  if (typeof window === "undefined") {
    return "en";
  }
  const storedLanguage = window.localStorage.getItem(LANGUAGE_KEY);
  return storedLanguage === "ru" || storedLanguage === "uk" ? storedLanguage : "en";
}

export function useI18n() {
  const [language, setLanguageState] = useState<Language>("en");

  useEffect(() => {
    function syncLanguage() {
      setLanguageState(readLanguage());
    }

    const timer = window.setTimeout(syncLanguage, 0);
    window.addEventListener("storage", syncLanguage);
    window.addEventListener(LANGUAGE_EVENT, syncLanguage);

    return () => {
      window.clearTimeout(timer);
      window.removeEventListener("storage", syncLanguage);
      window.removeEventListener(LANGUAGE_EVENT, syncLanguage);
    };
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = useCallback((nextLanguage: Language) => {
    window.localStorage.setItem(LANGUAGE_KEY, nextLanguage);
    setLanguageState(nextLanguage);
    window.dispatchEvent(new CustomEvent(LANGUAGE_EVENT));
  }, []);

  const t = useCallback(
    (key: TranslationKey) => translations[language][key] ?? translations.en[key] ?? key,
    [language],
  );

  return { language, setLanguage, t };
}
